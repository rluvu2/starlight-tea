/**
 * ─────────────────────────────────────────────────────────────────────
 *  별빛 찻집 · 팽주의 블렌딩 (Tea Blending) 규칙 (기획자 편집용)
 * ─────────────────────────────────────────────────────────────────────
 *  팽주는 유저의 이야기에서
 *    1위 열매 → 찻잎,  2위 열매 → 과일
 *  로 표현해 두 재료를 섞은 차를 권합니다. 순서가 의미를 가지며(찻잎 ↔ 과일),
 *  1위와 2위가 같은 열매여도 됩니다. 그래서 조합은 정확히 9 × 9 = 81가지입니다.
 *  (찻잎·과일·연결 이미지 표는 ingredients.js)
 *
 *  유저도 '나를 위한 차'에서 찻잎 하나와 과일 하나를 직접 고릅니다.
 *  찻잎과 과일이 둘 다 팽주의 블렌딩과 같을 때만 '일치'입니다.
 * ─────────────────────────────────────────────────────────────────────
 */

export const BLEND_RULE = {
  // 2위 열매를 과일로 쓰려면 2위 마음이 1위의 몇 배 이상이어야 하는지 (0.2 = 20%)
  // 이보다 약하면 2위는 무시하고, 1위 열매 하나로 찻잎과 과일을 모두 고릅니다.
  //   예) 사랑 50% · 온유 7%  → 7 ÷ 50 = 14%  (20% 미만) → 사랑 + 사랑 = "홍차 딸기차"
  //       사랑 60% · 온유 13% → 13 ÷ 60 ≈ 22% (20% 이상) → 사랑 + 온유 = "홍차 배차"
  secondRatio: 0.2,
};

// {leaf} 찻잎 이름, {fruit} 과일 이름, {leafImage}·{fruitImage} 각 열매의 연결 이미지
// {은/는} 같은 조사는 바로 앞 글자의 받침에 맞춰 자동으로 골라집니다.
export const BLEND_TEXT = {
  // 차 이름 규칙 — 예) 1위 화평, 2위 사랑 → "캐모마일 딸기차"
  name: "{leaf} {fruit}차",
  // 1위와 2위가 다른 열매일 때, 조언 카드에 덧붙는 한 줄
  blendLine: "{leaf}의 {leafImage}에 {fruit}의 {fruitImage}{을/를} 더했어요.",
  // 1위와 2위가 같은 열매일 때 (한 가지 마음이 유난히 짙을 때)
  pureLine: "{leaf}{과/와} {fruit} 모두 {leafImage}{을/를} 담았어요."
};
